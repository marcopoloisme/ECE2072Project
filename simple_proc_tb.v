`timescale 1ns/1ps

module simple_proc_tb;

    reg clk;
    reg rst;
    reg [8:0] din;

    wire [15:0] bus;

    wire [15:0] R0;
    wire [15:0] R1;
    wire [15:0] R2;
    wire [15:0] R3;
    wire [15:0] R4;
    wire [15:0] R5;
    wire [15:0] R6;
    wire [15:0] R7;

    //--------------------------------------------------
    // DUT
    //--------------------------------------------------

    simple_proc DUT (
        .clk(clk),
        .rst(rst),
        .din(din),
        .bus(bus),
        .R0(R0),
        .R1(R1),
        .R2(R2),
        .R3(R3),
        .R4(R4),
        .R5(R5),
        .R6(R6),
        .R7(R7)
    );

    //--------------------------------------------------
    // Clock
    //--------------------------------------------------

    initial begin
        clk = 0;
        forever #10 clk = ~clk;
    end

    //--------------------------------------------------
    // Monitor
    //--------------------------------------------------

    initial begin
        $monitor(
            "T=%0t Tick=%b Bus=%d R0=%d R1=%d R2=%d",
            $time,
            DUT.tick,
            bus,
            R0,
            R1,
            R2
        );
    end

    //--------------------------------------------------
    // Test Sequence
    //--------------------------------------------------

    initial begin

        //--------------------------------------------------
        // Reset
        //--------------------------------------------------

        rst = 1;
        din = 9'b0;

        #25;
        rst = 0;

        //--------------------------------------------------
        // MOVI R0, 5
        //--------------------------------------------------
        // opcode=111
        // Rx=000
        // imm=101

        din = 9'b111_000_101;

        #100;

        $display("After MOVI R0,5");
        $display("R0 = %d",R0);

        //--------------------------------------------------
        // MOVI R1, 3
        //--------------------------------------------------

        din = 9'b111_001_011;

        #100;

        $display("After MOVI R1,3");
        $display("R1 = %d",R1);

        //--------------------------------------------------
        // ADD R0,R1
        //--------------------------------------------------
        // R0 = R0 + R1
        // Expected 8

        din = 9'b001_000_001;

        #100;

        $display("After ADD R0,R1");
        $display("R0 = %d",R0);

        //--------------------------------------------------
        // ADDI R0,2
        //--------------------------------------------------
        // Expected 10

        din = 9'b010_000_010;

        #100;

        $display("After ADDI R0,2");
        $display("R0 = %d",R0);

        //--------------------------------------------------
        // SUB R0,R1
        //--------------------------------------------------
        // Expected 7

        din = 9'b011_000_001;

        #100;

        $display("After SUB R0,R1");
        $display("R0 = %d",R0);

        //--------------------------------------------------
        // End
        //--------------------------------------------------

        $display("--------------------------------");
        $display("FINAL VALUES:");
        $display("R0 = %d",R0);
        $display("R1 = %d",R1);
        $display("R2 = %d",R2);
        $display("--------------------------------");

        $stop;

    end

endmodule